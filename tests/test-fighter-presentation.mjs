import assert from 'node:assert/strict';
import { fighterHistory, renderFighterHistory, compactFighterRow, fighterProfile } from '../assets/js/fighter-presentation.js';
import { directoryFighterByName } from '../assets/js/fighter-directory.js';
import { setSpoilersEnabled, revealResult } from '../assets/js/spoilers.js';
const fighter = directoryFighterByName('Jiri Prochazka');
const event = {id:'one',type:'official',title:'Test UFC',date:'2026-01-01T00:00:00Z',status:'completed',bouts:[{red:'Jiří Procházka',blue:'Opponent',winner:'Jiří Procházka',method:'KO',round:2}]};
assert.equal(fighterHistory(fighter,[event,event]).length,1,'aliases match; duplicate events do not double the history');
assert.equal(fighterHistory(fighter,[{...event,type:'custom'}]).length,0);
assert.equal(fighterHistory(fighter,[{...event,date:'bad'}]).length,0);
assert.equal(fighterHistory(fighter,[{...event,bouts:[{red:'Other',blue:'Opponent'}]}]).length,0);
setSpoilersEnabled(true);
assert.ok(!renderFighterHistory(fighter,[event]).includes('Ganador:'));
revealResult(fighterHistory(fighter,[event])[0].key);
assert.ok(renderFighterHistory(fighter,[event]).includes('Ganador:'));
assert.ok(!renderFighterHistory(fighter,[{...event,status:'scheduled'}]).includes('Ganador:'));
assert.ok(renderFighterHistory(fighter,[]).includes('Todavía no hay combates'));
const options={events:[event],follow:'<button>Follow</button>',active:'history'};
const html=fighterProfile(fighter,options);
assert.ok(html.includes('id="fighter-panel-summary" hidden'));
assert.ok(!html.includes('id="fighter-panel-history" hidden'));
assert.ok(html.includes('Este historial puede no incluir toda su carrera.'));
assert.ok(!compactFighterRow({...fighter,first:'<script>',last:'&Test'},'').includes('<script>'));
assert.ok(compactFighterRow(fighter,'follow-marker').includes('follow-marker'));
console.log('Fighter presentation: aliases, deduplication, partial history, spoilers and safe rendering passed.');
