import { setSpoilersEnabled } from "../assets/js/spoilers.js";
setSpoilersEnabled(false);
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { followingActivity, followingFighterCard, followingBoutCard, boutPinKey, resolvePinnedBout } from '../assets/js/following.js';
import { directoryFighterByName } from '../assets/js/fighter-directory.js';
import { createStore, freshState, validateState } from '../assets/js/store.js';
import { eventCalendar } from '../assets/js/calendar.js';

const feed = JSON.parse(await readFile(new URL('../assets/data/ufc-events.json', import.meta.url)));
const oliveira = directoryFighterByName('Charles Oliveira');
const lopes = directoryFighterByName('Diego Lopes');
const nextEvent = feed.events.find(e => e.id === 'ufc-335');
const activity = followingActivity([oliveira.id, lopes.id, lopes.id], feed.events, Date.parse('2026-10-06T12:00:00Z'));
assert.equal(activity.fighters.length, 2);
const shared = activity.upcoming.filter(item => item.event.id === 'ufc-335' && item.bout.red === 'Charles Oliveira');
assert.equal(shared.length, 1);
assert.equal(shared[0].tracked.length, 2);
assert.ok(activity.upcoming.every((item, i, all) => !i || Date.parse(item.event.date) >= Date.parse(all[i-1].event.date)));
assert.ok(activity.recent.every(item => item.event.status === 'completed' && Date.parse(item.event.date) <= Date.parse('2026-10-06T12:00:00Z')));
assert.equal(followingActivity([], feed.events).upcoming.length, 0);
assert.equal(followingActivity([lopes.id], [{...nextEvent, type:'demo'}]).upcoming.length, 0);
assert.equal(followingActivity([lopes.id], [nextEvent, nextEvent], Date.parse('2026-10-06')).upcoming.length, 1);
assert.equal(followingActivity([lopes.id], [{...nextEvent, date:'2020-01-01',status:'announced'}]).upcoming.length, 0);
assert.equal(followingActivity([lopes.id], [{...nextEvent, status:'completed'}], Date.parse('2026-10-06')).recent.length, 0);
const alias = directoryFighterByName('Jiri Prochazka');
const aliasEvent = {...nextEvent, bouts:[{red:'Jiří Procházka',blue:'Diego Lopes',division:'Light Heavyweight'}]};
assert.equal(followingActivity([alias.id], [aliasEvent], Date.parse('2026-10-06')).upcoming.length, 1);
const empty = followingActivity([lopes.id], [], Date.parse('2026-10-06'));
assert.ok(followingFighterCard(lopes, empty, []).includes('Sin próximo combate anunciado'));
assert.ok(!followingBoutCard(shared[0]).includes('Ganador:'));
assert.ok(followingBoutCard({...shared[0], bout:{...shared[0].bout, winner:null,outcome:null}}, true).includes('Resultado aún no disponible'));
const copied = freshState(); copied.favorites = [oliveira.id, lopes.id];
assert.equal(validateState(copied), true);
assert.equal(validateState({...copied, favorites:[lopes.id,lopes.id]}), false);
assert.equal(validateState({...copied, favorites:['unknown']}), false);
const memory = new Map();
globalThis.localStorage = {getItem:k => memory.get(k) ?? null,setItem:(k,v) => memory.set(k,v)};
const store = createStore(); store.replace(copied);
assert.deepEqual(createStore().state.favorites, copied.favorites);
const old = freshState(); old.favorites=['topuria']; store.replace(old);
assert.deepEqual(createStore().state.favorites,['topuria']);
const calendar = eventCalendar(nextEvent, new Date('2026-10-06'));
assert.ok(calendar.includes('SUMMARY:UFC 335\r\n'));
assert.ok(calendar.includes('DTSTART:20261213T020000Z'));
assert.ok(!calendar.includes('DTEND') && !calendar.includes('imaginaria'));
assert.ok(calendar.includes('URL:https://www.ufc.com/event/ufc-335'));
assert.ok(calendar.split('\r\n').every(line => new TextEncoder().encode(line).length <= 75));
assert.ok(eventCalendar({...nextEvent,type:'demo'}).includes('(cartelera imaginaria)'));
console.log('PASS: following all profiles, shared bouts, aliases, chronology, no invented announcements, storage/import compatibility, official calendar');

const pin = boutPinKey(shared[0].event, shared[0].bout);
const reordered = {...nextEvent, bouts:[...nextEvent.bouts].reverse()};
assert.equal(resolvePinnedBout(pin, [reordered]).bout.red, shared[0].bout.red);
assert.equal(boutPinKey(nextEvent, {...shared[0].bout, red:shared[0].bout.blue, blue:shared[0].bout.red}), pin);
assert.equal(resolvePinnedBout(pin, []), null);
assert.equal(resolvePinnedBout(pin, [{...nextEvent, bouts:[]}]), null);
assert.ok(followingBoutCard(shared[0], false, pin).includes('aria-pressed="true">Quitar fijado'));
assert.ok(followingBoutCard(shared[0]).includes('aria-pressed="false">Fijar combate'));
store.state.pinnedBout = pin;
store.save();
assert.equal(createStore().state.pinnedBout, pin);
store.useScope('account-pin-test');
assert.equal(store.state.pinnedBout, null);
store.useScope();
assert.equal(store.state.pinnedBout, pin);
const legacy = freshState(); delete legacy.pinnedBout;
assert.equal(validateState(legacy), true);
assert.equal(validateState({...legacy, pinnedBout:{event:'invalid'}}), false);
assert.equal(validateState({...legacy, pinnedBout:'x'.repeat(501)}), false);
console.log('PASS: pinned bout persists, survives card reordering, handles unavailable bouts and remains isolated per account');
