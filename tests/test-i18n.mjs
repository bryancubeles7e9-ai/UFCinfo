import assert from 'node:assert/strict';
const memory = new Map();
globalThis.localStorage = { getItem:key=>memory.get(key), setItem:(key,value)=>memory.set(key,value) };
const { getLanguage, getLocale, setLanguage, translate } = await import('../assets/js/i18n.js');
assert.equal(getLanguage(),'es');
assert.equal(translate('Mi esquina'),'Mi esquina');
assert.equal(setLanguage('en'),true);
assert.equal(getLocale(),'en-US');
assert.equal(translate('Mi esquina'),'My corner');
assert.equal(translate('Peso ligero · Masculino'),'Lightweight · Men');
assert.equal(translate('10 de 10 luchadores + campeón'),'10 of 10 fighters + champion');
assert.equal(translate('Charles Oliveira'),'Charles Oliveira');
assert.equal(translate('  Exportar ↓'),'  Export ↓');
assert.equal(translate('Tu combate fijado'),'Your pinned fight');
assert.equal(memory.get('ufcinfo-language'),'en');
assert.equal(setLanguage('fr'),false);
assert.equal(getLanguage(),'en');
assert.equal((await import('../assets/js/i18n.js?reload')).getLanguage(),'en');
assert.equal(setLanguage('ca'),true);
assert.equal(getLocale(),'ca-ES');
assert.equal(translate('Mi esquina'),'El meu racó');
assert.equal(translate('Peso ligero · Masculino'),'Pes lleuger · Masculí');
assert.equal(translate('10 de 10 luchadores + campeón'),'10 de 10 lluitadors + campió');
assert.equal(translate('25 años'),'25 anys');
assert.equal(translate('2 publicaciones agrupadas'),'2 publicacions agrupades');
assert.equal(translate('  Exportar ↓'),'  Exporta ↓');
assert.equal(translate('Charles Oliveira'),'Charles Oliveira');
assert.equal(translate('Rankings'),'Rànquings');
assert.equal(translate('Overview'),'Inici');
assert.equal(memory.get('ufcinfo-language'),'ca');
assert.equal((await import('../assets/js/i18n.js?catalan-reload')).getLanguage(),'ca');
const {english}=await import('../assets/js/i18n/en.js');
const {catalan}=await import('../assets/js/i18n/ca.js');
for (const phrase of Object.keys(english)) assert.ok(catalan[phrase],`Missing Catalan: ${phrase}`);
setLanguage('es');
assert.equal(getLocale(),'es-ES');
assert.equal(translate('Mostrar resultado'),'Mostrar resultado');
globalThis.localStorage = {getItem(){throw Error();},setItem(){throw Error();}};
assert.equal(setLanguage('en'),true);
assert.equal((await import('../assets/js/i18n.js?unavailable')).getLanguage(),'es');
console.log('PASS: languages, complete phrases, dynamic labels, persistence, invalid selection and unavailable storage');
