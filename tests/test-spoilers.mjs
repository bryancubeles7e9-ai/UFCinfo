import assert from 'node:assert/strict';
import { spoilersEnabled, setSpoilersEnabled, revealResult, resultHidden } from '../assets/js/spoilers.js';
import { followingBoutCard, boutPinKey } from '../assets/js/following.js';
const event = {id:'spoiler-test',title:'UFC Test',date:'2026-01-01',location:'Madrid',status:'completed'};
const bout = {red:'Charles Oliveira',blue:'Diego Lopes',division:'Lightweight',winner:'Charles Oliveira',method:'SUBMISSION',round:'2',time:'1:23'};
const item = {event,bout,tracked:[]};
const key = boutPinKey(event,bout);
assert.equal(spoilersEnabled(),true);
let html = followingBoutCard(item,true,key);
assert.ok(html.includes('Mostrar resultado'));
assert.ok(!html.includes('Ganador:') && !html.includes('SUBMISSION') && !html.includes('1:23'));
revealResult(key);
html = followingBoutCard(item,true,key);
assert.ok(html.includes('Ganador: Charles Oliveira') && html.includes('SUBMISSION'));
assert.equal(resultHidden('other-bout'),true);
setSpoilersEnabled(false);
assert.ok(followingBoutCard(item,true).includes('SUBMISSION'));
setSpoilersEnabled(true);
assert.equal(resultHidden(key),true);
assert.ok(!followingBoutCard(item,true,key).includes('SUBMISSION'));
console.log('PASS: spoilers hidden by default, no result details in HTML, individual reveal and reactivation');
