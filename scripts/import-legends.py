#!/usr/bin/env python3
"""Apply the reviewed legends in docs/legends.json to the fighter catalogue.

Run from the repository root:  python3 scripts/import-legends.py
- Profiles missing from the catalogue are imported from their official UFC page.
- Every listed fighter is marked as a retired legend with its Hall of Fame wing and year,
  historical belts and editorial note (Spanish); the English and Catalan versions are
  written to assets/js/i18n/legend-notes.js.
- A fighter whose UFC page says "Active" is skipped and reported: a comeback needs review.
Use --check to only verify the UFC pages without writing anything.
"""
import importlib.util
import io
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('season', ROOT / 'scripts/import-season-fighters.py')
season = importlib.util.module_from_spec(spec)
spec.loader.exec_module(season)

DATA = ROOT / 'assets/js/fighter-directory-data.js'
MANIFEST = ROOT / 'docs/fighter-directory-sources.json'
PREFIX = '// Official UFC profiles; generated by scripts/import-fighter-directory.py.\n'


def status_tags(page):
    return [re.sub(r'<[^>]+>', '', tag).strip() for tag in re.findall(r'class="hero-profile__tag"[^>]*>(.*?)</p>', page, re.S)]


def save_banner(legend):
    """Hall of Fame banner, stored locally (1280 px) so the page does not depend on UFC's image server."""
    target = ROOT / f"assets/images/legends/{legend['id']}.jpg"
    if not target.exists() and legend.get('hallOfFameImage'):
        from PIL import Image  # pip install pillow
        from urllib.request import Request, urlopen
        with urlopen(Request(legend['hallOfFameImage'], headers={'User-Agent': 'Mozilla/5.0'}), timeout=60) as response:
            image = Image.open(io.BytesIO(response.read())).convert('RGB')
        image.thumbnail((1280, 720))
        target.parent.mkdir(parents=True, exist_ok=True)
        image.save(target, quality=82, optimize=True, progressive=True)
    return f"assets/images/legends/{legend['id']}.jpg" if target.exists() else None


def main():
    today = date.today().isoformat()
    legends = json.loads((ROOT / 'docs/legends.json').read_text())
    text = DATA.read_text()
    data = json.loads(text[text.index('=') + 1:].rstrip().rstrip(';'))
    manifest = json.loads(MANIFEST.read_text())
    by_id = {f['id']: f for f in data}
    manifest_by_id = {f['id']: f for f in manifest}
    skipped, added = [], []
    for legend in legends:
        page = season.fetch(legend['source'])
        tags = status_tags(page)
        if 'Active' in tags:
            skipped.append(f"{legend['name']} figura en activo en UFC.com; revisa su estado antes de marcarlo como leyenda.")
            continue
        if '--check' in sys.argv:
            continue
        athlete = manifest_by_id.get(legend['id']) or {'id': legend['id'], 'name': legend['name'], 'aliases': [legend['name']], 'source': legend['source']}
        fields = {
            'careerStatus': 'retired', 'legend': True,
            'legendSource': legend.get('hallOfFameSource') or athlete.get('legendSource') or legend['source'],
            'legendConsulted': today, 'retirementSource': athlete.get('retirementSource') or legend['source'],
            'hallOfFame': {'wing': legend['wing'], 'inducted': legend.get('inducted'), 'image': save_banner(legend)},
            'legacyNote': legend['note'],
        }
        if 'championships' in legend:
            source = legend.get('hallOfFameSource') or legend['source']
            fields['championships'] = [{'name': name, 'type': 'undisputed', 'status': 'former', 'source': source} for name in legend['championships']]
            fields['championshipHistoryConsulted'] = today
        athlete.update(fields)
        if legend['id'] not in manifest_by_id:
            manifest.append(athlete)
            manifest_by_id[legend['id']] = athlete
        if legend['id'] in by_id:
            by_id[legend['id']].update(fields)
            profile = by_id[legend['id']]
            if str(profile.get('image', '')).endswith('placeholder.svg') and fields['hallOfFame']['image']:
                profile['image'] = fields['hallOfFame']['image']
        else:
            profile = season.verified_profile(page, athlete, today)
            if profile['image'].endswith('placeholder.svg') and fields['hallOfFame']['image']:
                profile['image'] = fields['hallOfFame']['image']  # No portrait on the UFC profile: use the Hall of Fame photo.
            if profile.get('record') in ('0-0-0', None):
                profile['record'] = 'No indicado'  # UFC shows 0-0-0 for some pioneers.
            data.append(profile)
            by_id[legend['id']] = profile
            added.append(legend['name'])
    if '--check' not in sys.argv:
        DATA.write_text(PREFIX + 'export const additionalFighters = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
        MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        notes = {'en': {l['note']: l['noteEn'] for l in legends}, 'ca': {l['note']: l['noteCa'] for l in legends}}
        (ROOT / 'assets/js/i18n/legend-notes.js').write_text(
            '// English and Catalan versions of the legend notes; generated by scripts/import-legends.py from docs/legends.json.\n'
            'export const legendNotes = ' + json.dumps(notes, ensure_ascii=False, indent=1) + ';\n')
    for message in skipped:
        print(f'::warning::{message}')
    print(json.dumps({'legends': len(legends) - len(skipped), 'added': added, 'skipped': len(skipped)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
