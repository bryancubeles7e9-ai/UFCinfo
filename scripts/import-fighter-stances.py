"""Import a dated UFCStats snapshot, matching unique full names/aliases only.

Usage: python3 scripts/import-fighter-stances.py /path/to/ufcstats_data.csv
The CSV is the pinned TidyTuesday snapshot below, not live UFCStats data.
Unknown/ambiguous names remain unset; never guess from fighting style.
"""
import csv
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = "https://github.com/rfordatascience/tidytuesday/blob/107ff6c70de02dd807169e13aee7dc9d86ff88b6/data/2026/2026-07-07/ufcstats_data.csv"
VALID = {"Orthodox", "Southpaw", "Switch"}
CONSULTED = "2026-10-11"
# Individually checked sources for names missing a stance in the snapshot.
SUPPLEMENTS = {
    "ufc-jean-silva": ("Orthodox", "https://www.ufcstats.com/fighter-details/52ef95b5860fb28c", "UFC Stats"),
    "ufc-bilal-hasan": ("Switch", "https://ufcstats.com/fighter-details/5182316da3c1d891", "UFC Stats"),
    "ufc-gable-steveson": ("Orthodox", "https://ufcstats.com/fighter-details/f7e856a73c96048e", "UFC Stats"),
    "ufc-salahdine-parnasse": ("Southpaw", "https://www.cbssports.com/ufc/fighter/50057899/salahdine-parnasse/", "CBS Sports"),
    "ufc-roberto-soldic": ("Southpaw", "https://www.ufc.com.br/news/roberto-soldic-no-more-what-ifs-robocop-has-arrived-ufc-332", "UFC"),
}


def normalize(name):
    name = unicodedata.normalize("NFKD", name.replace("ł", "l")).encode("ascii", "ignore").decode()
    return re.sub("[^a-z0-9]", "", name.lower())


def match_stance(fighter, rows):
    names = {normalize(n) for n in [fighter["name"], *fighter.get("aliases", [])]}
    matches = [r for r in rows if normalize(r["name"]) in names]
    if len(matches) != 1 or matches[0].get("stance") not in VALID:
        return None
    return matches[0]["stance"]


def build(rows, fighters):
    result = {}
    for fighter in fighters:
        stance = match_stance(fighter, rows)
        source, label = SNAPSHOT, "UFC Stats · TidyTuesday (2026-07-07)"
        if fighter["id"] in SUPPLEMENTS:
            stance, source, label = SUPPLEMENTS[fighter["id"]]
        if stance:
            result[fighter["id"]] = dict(stance=stance, stanceSource=source,
                stanceSourceLabel=label, stanceConsulted=CONSULTED)
    return result


if __name__ == "__main__":
    with open(sys.argv[1]) as handle:
        rows = list(csv.DictReader(handle))
    fighters = json.loads((ROOT / "docs/fighter-directory-sources.json").read_text())
    result = build(rows, fighters)
    (ROOT / "assets/js/fighter-stance-data.js").write_text(
        "// Dated source evidence; generated by scripts/import-fighter-stances.py.\n"
        + "export const fighterStances = " + json.dumps(result, ensure_ascii=False, indent=2) + ";\n")
    print(f"Guardias documentadas: {len(result)}/{len(fighters)}")
    print("Sin dato:", [f["name"] for f in fighters if f["id"] not in result])
